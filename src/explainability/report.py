"""Markdown + JSON explanation reports, one per model version."""

from __future__ import annotations

import json
from typing import Dict, List, Sequence

from explainability.quality import QualityGateResult


def _ranked_table(importance: Dict[str, float]) -> str:
    lines = ["| Rank | Feature | Importance |", "|---:|---|---|"]
    for i, (name, value) in enumerate(
        sorted(importance.items(), key=lambda kv: -kv[1]), start=1
    ):
        lines.append(f"| {i} | {name} | {value:.4f} |")
    return "\n".join(lines)


def build_report_markdown(
    model_version: str,
    dataset_hash: str,
    feature_names: Sequence[str],
    importance: Dict[str, float],
    mean_effect: Dict[str, float],
    quality: QualityGateResult,
    drift_summary: str = "No reference ranking supplied; drift check skipped.",
) -> str:
    lines = [
        f"# Explanation Report — model `{model_version}`",
        "",
        f"- Dataset snapshot hash: `{dataset_hash}`",
        f"- Features: {', '.join(feature_names)}",
        "",
        "## Permutation importance",
        "",
        _ranked_table(importance),
        "",
        "## Mean absolute effect",
        "",
        _ranked_table(mean_effect),
        "",
        "## Quality gates",
        "",
        f"- Faithfulness (Pearson): {quality.faithfulness:.3f} "
        f"— {'PASS' if quality.faithfulness_pass else 'FAIL'}",
        f"- Stability (Spearman across seeds): {quality.stability:.3f} "
        f"— {'PASS' if quality.stability_pass else 'FAIL'}",
        f"- Monotonicity spot-check: {quality.monotonicity:.3f} "
        f"— {'PASS' if quality.monotonicity_pass else 'FAIL'}",
        "",
        f"**Promotion allowed: {'YES' if quality.promotion_allowed else 'NO'}**",
        "",
        "## Explanation drift",
        "",
        drift_summary,
        "",
        "_Generated by the Model Explainability Platform. Explanations are "
        "versioned in the explanation registry alongside this report._",
    ]
    return "\n".join(lines)


def build_report_json(
    model_version: str,
    dataset_hash: str,
    importance: Dict[str, float],
    mean_effect: Dict[str, float],
    quality: QualityGateResult,
    drift: Dict[str, object] | None = None,
) -> Dict[str, object]:
    return {
        "model_version": model_version,
        "dataset_hash": dataset_hash,
        "permutation_importance": importance,
        "mean_absolute_effect": mean_effect,
        "quality_gates": {
            "faithfulness": quality.faithfulness,
            "stability": quality.stability,
            "monotonicity": quality.monotonicity,
            "promotion_allowed": quality.promotion_allowed,
        },
        "drift": drift,
    }


def render_report_json(payload: Dict[str, object]) -> str:
    return json.dumps(payload, indent=2, sort_keys=True)
